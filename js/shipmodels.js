function partGeometry(part, len) {
  let g;
  if (part.t === 'box') g = new THREE.BoxGeometry(part.s[0] * len, part.s[1] * len, part.s[2] * len);
  else {
    g = new THREE.CylinderGeometry(part.s[0] * len, part.s[1] * len, part.s[2] * len, part.s[0] === 0 ? 8 : 10);
    if (part.axis === 'x' || !part.axis) g.rotateZ(-Math.PI / 2); else if (part.axis === 'z') g.rotateX(Math.PI / 2);
  }
  if (part.rot) g.rotateX(part.rot[0]), g.rotateY(part.rot[1]), g.rotateZ(part.rot[2]);
  g.translate(part.p[0] * len, part.p[1] * len, part.p[2] * len);
  return g.toNonIndexed();
}

function mergeParts(parts, len) {
  const pos = [], nor = [], col = [];
  for (const part of parts) {
    const g = partGeometry(part, len);
    const pa = g.attributes.position.array, na = g.attributes.normal.array;
    for (let i = 0; i < pa.length; i++) { pos.push(pa[i]); nor.push(na[i]); }
    g.dispose();
  }
  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  geo.setAttribute('normal', new THREE.Float32BufferAttribute(nor, 3));
  return geo;
}

const cache = new Map();
// returns { hull: BufferGeometry, glow: BufferGeometry, extraGlow: [{geo, color}] }
export function shipGeometry(type, len) {
  const key = type + ':' + len;
  if (cache.has(key)) return cache.get(key);
  const spec = SPECS[type];
  const hull = mergeParts(spec.filter(p => !p.glow), len);
  const glow = mergeParts(spec.filter(p => p.glow && !p.col), len);
  const extra = {};
  for (const p of spec) if (p.glow && p.col) (extra[p.col] = extra[p.col] || []).push(p);
  const extraGlow = Object.entries(extra).map(([c, parts]) => ({ color: +c, geo: mergeParts(parts, len) }));
  const r = { hull, glow, extraGlow };
  cache.set(key, r);
  return r;
}
